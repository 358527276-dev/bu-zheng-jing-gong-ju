// ===== 脱单概率 =====
function loveProbability(info) {
  const baseProb = Math.floor(Math.random() * 40) + 40;
  let prob = baseProb;
  
  const analysis = [];
  
  if (info.age) {
    if (info.age >= 20 && info.age <= 28) {
      prob += 5;
      analysis.push('🌸 正值黄金年龄，脱单机会多多');
    } else if (info.age > 28 && info.age <= 35) {
      prob += 2;
      analysis.push('💪 成熟稳重，是你的加分项');
    }
  }
  
  if (info.personality) {
    if (['外向', '活泼', '开朗'].includes(info.personality)) {
      prob += 8;
      analysis.push('✨ 外向开朗的性格很容易吸引异性');
    } else if (['内向', '安静', '慢热'].includes(info.personality)) {
      prob += 3;
      analysis.push('🌙 慢热型虽然进度慢，但更容易遇到真爱');
    }
  }
  
  if (info.hobby) {
    prob += 5;
    analysis.push('🎯 有兴趣爱好的人更有魅力');
  }
  
  prob = Math.min(99, Math.max(10, prob));
  
  const suggestions = [
    '多参加社交活动，缘分是需要主动创造的',
    '提升自己，花香蝶自来',
    '打开心扉，给别人一个了解你的机会',
    '扩大圈子，走出舒适区',
    '保持自信，你值得被爱'
  ];
  
  return {
    probability: prob,
    analysis,
    suggestions: suggestions.sort(() => Math.random() - 0.5).slice(0, 3),
    timeline: getTimeline(prob),
    summary: getProbSummary(prob)
  };
}

function getTimeline(prob) {
  if (prob >= 90) return '快了！最近3个月内很有可能遇到心仪的对象';
  if (prob >= 75) return '半年内有望脱单，多留意身边的人';
  if (prob >= 60) return '今年内有机会，耐心等待';
  if (prob >= 40) return '还需要一些时间，先专注提升自己吧';
  return '路漫漫其修远兮，缘分未到莫强求';
}

function getProbSummary(prob) {
  if (prob >= 90) return '脱单在望！爱情的小火苗已经熊熊燃烧啦🔥';
  if (prob >= 75) return '形势大好！再加把劲，甜甜的爱情就要轮到你了💕';
  if (prob >= 60) return '机会不小！主动一点，故事就开始了😊';
  if (prob >= 40) return '不温不火！随缘就好，该来的总会来的🌱';
  return '道阻且长！先好好爱自己，对的人在路上🚶';
}

